// Publishes partner logos to public/brand/partners and writes a typed manifest.
// Classifies each file: an SVG counts as vector only if it does not embed a raster image.
// Fails if partners.json and the source folder disagree.
import { createHash } from 'node:crypto'
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { extname, join } from 'node:path'

const check = process.argv.includes('--check')
const sourceDir = 'assets/source/CD_Partner_Logos'
const dataFile = 'src/brand/partners.json'
const outFile = 'src/brand/partners.generated.ts'
const publicDir = 'public/brand/partners'

const data = JSON.parse(readFileSync(dataFile, 'utf8'))
const onDisk = new Set(readdirSync(sourceDir).filter((name) => !name.startsWith('.')))
const referenced = new Set(data.partners.flatMap((p) => p.files.map((f) => f.file)))
for (const file of referenced)
  if (!onDisk.has(file)) throw new Error(`${dataFile} lists ${file}, which is not in ${sourceDir}`)
for (const file of onDisk)
  if (!referenced.has(file)) throw new Error(`${sourceDir}/${file} is not listed in ${dataFile}`)

function pixelSize(bytes, format) {
  if (format === 'png') return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) }
  // JPEG: walk segments to the first start-of-frame marker.
  let offset = 2
  while (offset < bytes.length) {
    const marker = bytes[offset + 1]
    const length = bytes.readUInt16BE(offset + 2)
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { width: bytes.readUInt16BE(offset + 7), height: bytes.readUInt16BE(offset + 5) }
    }
    offset += 2 + length
  }
  throw new Error('Could not read JPEG size')
}

const partners = data.partners
  .map((partner) => {
    const files = partner.files.map((entry) => {
      const bytes = readFileSync(join(sourceDir, entry.file))
      const ext = extname(entry.file).slice(1).toLowerCase()
      const format = ext === 'jpeg' ? 'jpg' : ext
      const svg = format === 'svg' ? bytes.toString('utf8') : ''
      const vector = format === 'svg' && !/<image\b/i.test(svg)
      const size =
        format === 'svg'
          ? (() => {
              const [, , width, height] = (svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 0 0').split(/[\s,]+/).map(Number)
              return { width, height }
            })()
          : pixelSize(bytes, format)
      return {
        file: entry.file,
        href: `/brand/partners/${entry.file}`,
        format,
        vector,
        note: entry.note,
        originalOn: entry.originalOn ?? 'light',
        ...size,
        bytes: bytes.length,
        sha256: createHash('sha256').update(bytes).digest('hex'),
      }
    })
    return { id: partner.id, name: partner.name, files, vector: files.find((f) => f.vector)?.file ?? null }
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }))

const output = `// Generated by scripts/build-partners.mjs from ${dataFile}. Do not edit.
import type { Partner } from './partner-types'

export const partners: readonly Partner[] = ${JSON.stringify(partners, null, 2)}
`

if (check) {
  if (readFileSync(outFile, 'utf8') !== output) {
    console.error(`${outFile} is out of date. Run pnpm assets.`)
    process.exit(1)
  }
} else {
  writeFileSync(outFile, output)
}

rmSync(publicDir, { recursive: true, force: true })
mkdirSync(publicDir, { recursive: true })
for (const file of onDisk) cpSync(join(sourceDir, file), join(publicDir, file))
const vectorCount = partners.filter((p) => p.vector).length
console.log(`Published ${onDisk.size} partner files: ${vectorCount} of ${partners.length} partners have vector logos`)
